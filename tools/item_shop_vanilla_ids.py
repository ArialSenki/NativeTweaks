"""Writes src/item_shop_vanilla_ids.inc: the item ids of the vanilla regulation.

The item shop (F11) puts every item whose id is not in these lists in the
section of the overhaul or mod that adds it (Reforged, Convergence, ...).

usage: python tools/item_shop_vanilla_ids.py <vanilla regulation.bin> [out.inc]
needs: pycryptodome, zstandard (the regulation is AES-CBC + DCX ZSTD/DFLT)
"""
import struct
import sys
import zlib
from pathlib import Path

from Crypto.Cipher import AES
import zstandard

KEY = bytes.fromhex("99BFFC366A6BC8C6F5827D093602D676C42892A01C207FB024D3AF4E493FEF99")
# param, C++ array name, keep only base weapons (id % 10000 == 0)
PARAMS = (
    ("EquipParamWeapon", "kVanillaWeapons", True),
    ("EquipParamProtector", "kVanillaProtectors", False),
    ("EquipParamAccessory", "kVanillaAccessories", False),
    ("EquipParamGoods", "kVanillaGoods", False),
    ("EquipParamGem", "kVanillaGems", False),
)


def load(path):
    raw = Path(path).read_bytes()
    body = raw[16:]
    data = AES.new(KEY, AES.MODE_CBC, raw[:16]).decrypt(body[: len(body) - len(body) % 16])
    usize = struct.unpack(">I", data[0x1C:0x20])[0]
    csize = struct.unpack(">I", data[0x20:0x24])[0]
    payload = data[0x4C : 0x4C + csize]
    fmt = data[0x28:0x2C]
    if fmt == b"ZSTD":
        data = zstandard.ZstdDecompressor().decompress(payload, max_output_size=usize)
    elif fmt == b"DFLT":
        data = zlib.decompress(payload)
    else:
        raise SystemExit(f"unsupported DCX {fmt}")
    count = struct.unpack_from("<i", data, 0x0C)[0]
    header = struct.unpack_from("<q", data, 0x20)[0]
    files = {}
    for i in range(count):
        o = 0x40 + i * header
        size = struct.unpack_from("<q", data, o + 8)[0]
        offset = struct.unpack_from("<I", data, o + 0x18)[0]
        name_offset = struct.unpack_from("<I", data, o + 0x20)[0]
        end = name_offset
        while data[end : end + 2] != b"\0\0":
            end += 2
        name = data[name_offset:end].decode("utf-16-le").split("\\")[-1]
        files[name] = data[offset : offset + size]
    return files


def ids(param):
    count = struct.unpack_from("<H", param, 0x0A)[0]
    return [struct.unpack_from("<i", param, 0x40 + i * 24)[0] for i in range(count)]


def ranges(values, step):
    out = []
    for v in sorted(set(values)):
        if out and v == out[-1][1] + step:
            out[-1][1] = v
        else:
            out.append([v, v])
    return out


def main():
    files = load(sys.argv[1])
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parents[1] / "src" / "item_shop_vanilla_ids.inc"
    lines = [
        "// Generated by tools/item_shop_vanilla_ids.py from the vanilla regulation.bin",
        "// (Elden Ring 2.7.2.0). Items a later patch adds count as mod items until this is regenerated.",
        "// {first, last} id ranges, sorted; weapons in steps of 10000 (base ids only).",
    ]
    for param, name, weapons in PARAMS:
        values = [i for i in ids(files[param + ".param"]) if i > 0 and (not weapons or i % 10000 == 0)]
        r = ranges(values, 10000 if weapons else 1)
        lines.append(f"// {param}: {len(values)} ids")
        lines.append(f"constexpr VanillaIdRange {name}[]{{")
        row = []
        for first, last in r:
            row.append(f"{{{first}, {last}}}")
            if len(row) == 8:
                lines.append("    " + ", ".join(row) + ",")
                row = []
        if row:
            lines.append("    " + ", ".join(row) + ",")
        lines.append("};")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(out, sum(1 for _ in lines))


if __name__ == "__main__":
    main()
